export const translateSchemeText = (text: string, lang: LanguageCode): string => {
  if (lang === 'en') return text;
  if (schemeTranslations[text] && schemeTranslations[text][lang]) {
    return schemeTranslations[text][lang];
  }
  return text;
};

export const getTranslatedSchemes = (schemes: Scheme[], lang: LanguageCode): Scheme[] => {
  if (lang === 'en') return schemes;
  return schemes.map(scheme => ({
    ...scheme,
    name: translateSchemeText(scheme.name, lang),
    headline: translateSchemeText(scheme.headline, lang),
    // Fallback translation mechanism for other fields could be added here
  }));
};
